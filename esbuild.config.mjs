import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const lezerRequire = createRequire(require.resolve("@lezer/javascript"));
const lezerLicenses = [...new Set(["javascript", "common", "highlight", "lr"].map((name) => {
  const entry = pathToFileURL(lezerRequire.resolve(`@lezer/${name}`));
  return readFileSync(new URL("../LICENSE", entry), "utf8").trim();
}))].join("\n\n");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD

Bundled Lezer packages: @lezer/javascript, @lezer/common, @lezer/highlight, @lezer/lr.
${lezerLicenses}
*/`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: banner
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    ...builtins
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod
});

if (prod) {
  await context.rebuild();
  process.exit(0);
}

await context.watch();
