let current: AppLanguage = "zh";

export function setAppLanguage(language: AppLanguage): void {
  current = language === "en" ? "en" : "zh";
}

export function t(key: MessageKey, vars?: Vars): string {
  const template = (current === "en" ? en : zh)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function displayLearningStatus(status: string): string {
  if (status === "已学习") return t("statusLearned");
  if (status === "未学习") return t("statusUnlearned");
  return status;
}
